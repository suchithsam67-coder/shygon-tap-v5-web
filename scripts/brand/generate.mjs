// Writes every brand asset from the vector logo and the card designs:
//
//   public/brand/*.svg            logo files (mark, wordmark, lockup)
//   public/favicon.ico|svg        browser icons
//   public/icons/*.png            touch, PWA and maskable icons
//   public/logo.png               the lockup on black
//   public/assets/cards/*.svg     card art: 4 products x 3 materials x
//                                 2 finishes x front/back
//   ... and the six Design Collection cards (scripts/brand/concepts.mjs)
//
//   node scripts/brand/generate.mjs [--admin ../shygon-tap-v5-admin]
//
// With --admin it also writes the admin app's icon, adaptive icon, splash,
// web favicon and Android notification icon.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { GOLD, LOCKUP, MARK, WORDMARK } from './logo.mjs';
import { canvas, coverage, fill, flatten, roundRect, writeIco, writePng } from './raster.mjs';
import { renderCard } from './cards.mjs';
import { CONCEPTS, renderConcept } from './concepts.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const pub = (...p) => path.join(ROOT, 'public', ...p);
const INK = '#000000';

// The site URL printed on card backs, and the company name, from the same
// places the app reads them.
const envFile = fs.existsSync(path.join(ROOT, '.env')) ? fs.readFileSync(path.join(ROOT, '.env'), 'utf8') : '';
const envSite = (process.env.VITE_SITE_URL || envFile.match(/^VITE_SITE_URL=(.+)$/m)?.[1] || '').trim();
const SITE = /^https:\/\/(?!localhost)/.test(envSite) ? envSite.replace(/\/+$/, '') : 'https://shygontech.com';
const COMPANY = fs.readFileSync(path.join(ROOT, 'src/lib/site.ts'), 'utf8').match(/COMPANY_NAME = '([^']+)'/)[1];

// ------------------------------------------------------------------ logos

const svgDoc = (w, h, body, label = 'SHYGON') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" role="img" aria-label="${label}"><title>${label}</title>${body}</svg>\n`;

fs.mkdirSync(pub('brand'), { recursive: true });
fs.writeFileSync(pub('brand/shygon-mark.svg'), svgDoc(MARK.width, MARK.height, `<path fill="${GOLD}" fill-rule="evenodd" d="${MARK.d}"/>`));
fs.writeFileSync(pub('brand/shygon-wordmark.svg'), svgDoc(WORDMARK.width, WORDMARK.height, `<path fill="${GOLD}" d="${WORDMARK.d}"/>`));
fs.writeFileSync(
  pub('brand/shygon-logo.svg'),
  svgDoc(LOCKUP.width, LOCKUP.height, `<g fill="${GOLD}"><path fill-rule="evenodd" d="${LOCKUP.mark}"/><path d="${LOCKUP.word}"/></g>`),
);
// Lockup on its black tile, as in the master artwork.
{
  const pad = 180;
  const w = LOCKUP.width + pad * 2;
  const h = LOCKUP.height + pad * 2;
  const side = Math.max(w, h);
  fs.writeFileSync(
    pub('brand/shygon-logo-on-black.svg'),
    svgDoc(side, side, `<rect width="${side}" height="${side}" fill="${INK}"/><g transform="translate(${(side - LOCKUP.width) / 2} ${(side - LOCKUP.height) / 2})" fill="${GOLD}"><path fill-rule="evenodd" d="${LOCKUP.mark}"/><path d="${LOCKUP.word}"/></g>`),
  );
}

// The paths for the app's inline <BrandMark />, rounded to whole units of the
// 428 x 798 artwork (invisible at any on-screen size, half the bytes). The
// loading screen in index.html inlines the same mark.
const compact = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(parseFloat(n))));
fs.writeFileSync(
  path.join(ROOT, 'src/components/brand/logoPaths.ts'),
  `// Generated by scripts/brand/generate.mjs from scripts/brand/logo.mjs. Do not edit.
export const MARK_VIEWBOX = '0 0 ${MARK.width} ${MARK.height}';
export const MARK_PATH =
  '${compact(MARK.d)}';
export const WORDMARK_VIEWBOX = '0 0 ${WORDMARK.width} ${WORDMARK.height}';
export const WORDMARK_PATH =
  '${compact(WORDMARK.d)}';
`,
);
{
  // Keep the loading screen's inline mark in step with the artwork.
  const indexFile = path.join(ROOT, 'index.html');
  const html = fs.readFileSync(indexFile, 'utf8');
  const svg = `<svg class="boot-logo" viewBox="0 0 ${MARK.width} ${MARK.height}" aria-hidden="true"><path fill-rule="evenodd" d="${compact(MARK.d)}"/></svg>`;
  const next = html.replace(/<svg class="boot-logo"[\s\S]*?<\/svg>/, svg);
  if (next !== html) fs.writeFileSync(indexFile, next);
}

// ------------------------------------------------------------------ icons

/** The mark (or lockup), `frac` of the canvas tall, centred. */
function drawLogo(img, frac, colour, { lockup = false } = {}) {
  const n = img.height;
  const srcH = lockup ? LOCKUP.height : MARK.height;
  const srcW = lockup ? LOCKUP.width : MARK.width;
  const scale = (n * frac) / srcH;
  const dx = (img.width - srcW * scale) / 2;
  const dy = (n - srcH * scale) / 2;
  const opts = { scale, dx, dy, tolerance: 0.15 };
  const polys = lockup ? [...flatten(LOCKUP.mark, opts), ...flatten(LOCKUP.word, opts)] : flatten(MARK.d, opts);
  return fill(img, coverage(polys, img.width, img.height, n < 64 ? 16 : 8), colour);
}

/** Black rounded tile with the gold mark: favicons. */
function tile(n, { radius = 0.22, frac = 0.74 } = {}) {
  const img = canvas(n, n, null);
  fill(img, roundRect(n, n, 0, 0, n, n, n * radius), INK);
  return drawLogo(img, frac, GOLD);
}

/** Full-bleed black square: platforms that round the corners themselves. */
function square(n, frac) {
  return drawLogo(canvas(n, n, INK), frac, GOLD);
}

fs.mkdirSync(pub('icons'), { recursive: true });
writeIco(pub('favicon.ico'), [tile(16, { frac: 0.8 }), tile(32), tile(48)]);
writePng(pub('icons/favicon-32.png'), tile(32));
writePng(pub('icons/apple-touch-icon.png'), square(180, 0.62));
writePng(pub('icons/icon-192.png'), square(192, 0.64));
writePng(pub('icons/icon-512.png'), square(512, 0.64));
writePng(pub('icons/icon-maskable-512.png'), square(512, 0.5));
writePng(pub('logo.png'), drawLogo(canvas(1024, 1024, INK), 0.66, GOLD, { lockup: true }));
fs.writeFileSync(
  pub('favicon.svg'),
  svgDoc(64, 64, `<rect width="64" height="64" rx="14" fill="${INK}"/><g transform="translate(${(64 - MARK.width * (47 / MARK.height)) / 2} 8.5) scale(${(47 / MARK.height).toFixed(5)})"><path fill="${GOLD}" fill-rule="evenodd" d="${MARK.d}"/></g>`),
);

// ------------------------------------------------------------------ cards

const PRODUCTS = ['business', 'restaurant', 'event', 'google-review'];
const MATERIALS = ['pvc', 'metal', 'transparent'];
fs.mkdirSync(pub('assets/cards'), { recursive: true });
let bytes = 0;
const written = [];
for (const product of PRODUCTS) {
  for (const material of MATERIALS) {
    for (const finish of ['standard', 'premium']) {
      for (const face of ['front', 'back']) {
        const name = `${product}-${material}${finish === 'premium' ? '-premium' : ''}${face === 'back' ? '-back' : ''}.svg`;
        const svg = renderCard({ product, material, finish, face, site: SITE, company: COMPANY });
        fs.writeFileSync(pub('assets/cards', name), svg);
        bytes += svg.length;
        written.push(name);
      }
    }
  }
}
console.log(`cards: ${written.length} files, ${(bytes / 1024).toFixed(0)} KB, back URL ${SITE}/shygontap, company "${COMPANY}"`);

// The Design Collection: six more cards, every material, finish and face.
let collection = 0;
for (const [key, concept] of Object.entries(CONCEPTS)) {
  for (const material of MATERIALS) {
    for (const finish of ['standard', 'premium']) {
      for (const face of ['front', 'back']) {
        const name = `${concept.product}-${material}${finish === 'premium' ? '-premium' : ''}${face === 'back' ? '-back' : ''}.svg`;
        const svg = renderConcept({ key, material, finish, face, site: SITE, company: COMPANY });
        fs.writeFileSync(pub('assets/cards', name), svg);
        bytes += svg.length;
        collection++;
      }
    }
  }
}
console.log(`design collection: ${collection} files; all card art ${(bytes / 1024).toFixed(0)} KB`);

// ------------------------------------------------------------------ admin

const adminAt = process.argv.indexOf('--admin');
if (adminAt > -1) {
  const admin = path.resolve(ROOT, process.argv[adminAt + 1]);
  const a = (...p) => path.join(admin, 'assets', ...p);
  if (!fs.existsSync(a())) throw new Error(`No assets folder at ${a()}`);
  writePng(a('icon.png'), square(1024, 0.6));
  // Android adaptive icon: transparent foreground inside the 66% safe zone,
  // on the black background set in app.json.
  writePng(a('adaptive-icon.png'), drawLogo(canvas(1024, 1024, null), 0.46, GOLD));
  writePng(a('splash-icon.png'), drawLogo(canvas(1024, 1024, null), 0.9, GOLD, { lockup: true }));
  writePng(a('favicon.png'), tile(196, { radius: 0.2, frac: 0.72 }));
  // Android draws notification icons as a white silhouette.
  writePng(a('notification-icon.png'), drawLogo(canvas(96, 96, null), 0.78, '#ffffff'));
  console.log('admin assets written to', a());
}
console.log('done');
